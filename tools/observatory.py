def read_export(path: Path) -> ExportRead:
    """Read one per-dispatch export file, counting rather than swallowing bad lines.

    A truncated line is ordinary in an appended file whose writer can be killed
    mid-line, and four exist in the current archive. Skipping one silently is what
    #496 exists to prevent: a parse boundary must report. So each bad line increments
    a counter its caller names the file for, and the rebuild continues.
    """
    batches: list[Mapping[str, Any]] = []
    malformed = 0
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if not line.strip():
            continue
        try:
            batch = json.loads(line)
        except json.JSONDecodeError:
            malformed += 1
            continue
        if isinstance(batch, dict):
            batches.append(batch)
        else:
            malformed += 1
    return ExportRead(tuple(batches), malformed)


def _log_record_spend(items: Sequence[ledger.Item]) -> dict[str, int]:
    """Total the token counts log records carry as attributes, per bucket.

    The encoding Claude Code actually emits per request: `claude_code.api_request`
    records with `input_tokens` / `output_tokens` and the two cache halves. Counted
    only when no metric or span carried the same dispatch's spend — a lane that emits
    both encodings for one dispatch would be double-booked by a reader that summed
    them, and the selection lives at the caller.
    """
    totals: dict[str, int] = {}
    for item in items:
        if item.kind != "log":
            continue
        for source, bucket in LOG_TOKEN_KEYS.items():
            value = item.attrs.get(source)
            if isinstance(value, (int, float)) and not isinstance(value, bool):
                totals[bucket] = totals.get(bucket, 0) + int(value)
    return totals


def _has_metric_or_span_spend(items: Sequence[ledger.Item]) -> bool:
    """Say whether any token metric or token-bearing span exists among the items.

    Presence, not value: a metric that reports a true zero must still select the
    metric encoding rather than falling through to the log-record half, because the
    zero is a measurement and not a silence (#225's distinction, applied here).
    """
    for item in items:
        if item.kind == "metric" and item.name in ledger.TOKEN_METRICS:
            return True
        if item.kind == "span" and any(
            key in item.attrs for keys in ledger.SPAN_TOKEN_KEYS.values() for key in keys
        ):
            return True
    return False


def read_spend(items: Sequence[ledger.Item]) -> Spend:
    """Read one dispatch's spend in whichever encoding its records actually carry.

    The two encodings are selected, never summed: a dispatch whose metrics reported
    the spend is priced from its metrics, and only a dispatch with no metric or span
    carrying spend falls to the log-record half. A dispatch with neither gets a
    reason and no number — an absence is never a zero.
    """
    if _has_metric_or_span_spend(items):
        usage = ledger.normalise_usage(items)
        return Spend(
            ENCODING_METRIC,
            usage.input_tokens,
            usage.output_tokens,
            usage.cache_read_tokens,
            usage.cache_creation_tokens,
            None,
        )
    log_totals = _log_record_spend(items)
    if log_totals:
        return Spend(
            ENCODING_LOG_RECORDS,
            log_totals.get("input_tokens", 0),
            log_totals.get("output_tokens", 0),
            log_totals.get("cache_read_tokens", 0),
            log_totals.get("cache_creation_tokens", 0),
            None,
        )
    return Spend(None, None, None, None, None, NO_TOKEN_RECORDS_REASON)


def _row_spend(row: Mapping[str, Any] | None) -> Spend:
    """Read one dispatch's spend from its materialised ledger row, or say it cannot.

    The fallback for a pruned export file. A row with token numbers carries the metric
    and span encodings' figures verbatim — `normalise_usage` is the same reader the
    metric half above uses — so a pruned dispatch's spend survives except where the row
    cannot answer: all-zero usage is ambiguous (a true zero, a silence, or a
    log-record-only dispatch whose numbers never reached the row), and an absence is
    never resolved to a zero.
    """
    if row is None:
        return Spend(None, None, None, None, None, ROW_UNREADABLE)
    usage = row.get("usage")
    buckets = (
        {bucket: usage.get(bucket) for bucket in LOG_TOKEN_KEYS.values()}
        if isinstance(usage, dict)
        else {}
    )
    if not any(isinstance(value, int) and value for value in buckets.values()):
        return Spend(None, None, None, None, None, ROW_SPEND_NOT_DERIVABLE)
    return Spend(
        ENCODING_METRIC,
        int(buckets.get("input_tokens") or 0),
        int(buckets.get("output_tokens") or 0),
        int(buckets.get("cache_read_tokens") or 0),
        int(buckets.get("cache_creation_tokens") or 0),
        None,
    )


class LandingJournals(NamedTuple):
    """The journal halves the landing preference reads, computed once per rebuild.

    `produced` indexes the landing rows by issue, commits only; `damaged` holds every
    issue whose journal exists and read as damage — the set that keeps a wrecked
    journal from passing for an absent one. `journalled` is every issue with a readable
    landing event or a damaged journal, so coverage can distinguish no journal from a
    journal that cannot answer.
    """

    produced: Mapping[int, tuple[str, ...]]
    damaged: frozenset[int]
    journalled: frozenset[int]


def _journalled_landing(
    repo: Path, issue: int, produced: Sequence[str], damaged: frozenset[int]
) -> ledger.Landing:
    """Answer an issue's landing from its landings journal, which owns it where it exists.

    The journal is the record of the loop that gated the landing, so where it names
    the produced commit the projection reports that commit and the git derivation
    never runs — #563's defect was the derivation admitting a follow-up's
    credit-bearing prose as the landing, and two of five landings corrupted an older
    issue's row with it. Where the journal cannot answer — it would not read, or
    records landings while naming no commit, or names commits this checkout does not
    hold — the answer is a null with a reason and never a quiet fallback to the
    derivation, because a damaged record rendering as a healthy git answer is the
    absent-value shape this store has already closed eleven instances of.
    """
    if not produced:
        reason = (
            "the landings journal could not be read"
            if issue in damaged
            else NO_COMMIT_RELATION_REASON
        )
        return ledger.Landing(None, 0, reason)
    commits = tuple(sorted(set(produced)))
    sha, reason = _newest_landed_sha(repo, commits)
    if sha is None:
        return ledger.Landing(None, 0, str(reason))
    return ledger.Landing(
        sha,
        len(commits),
        f"journalled as produced by {len(commits)} landing(s) of #{issue}",
        commits,
    )


def _landing_journals(landing_read: LandingRead) -> LandingJournals:
    """Read the journal halves the landing preference needs out of one `LandingRead`.

    `produced` indexes the landing rows by issue, commits only, order-free. `damaged`
    comes from `read_landings`' damage counts, keyed `"<issue>/landings.jsonl"`: an
    issue whose journal is entirely damage has no landing rows, so without this set
    it would be indistinguishable from an issue that never journalled — and falling
    back to the git derivation there is precisely the silent repair this reader
    refuses.
    """
    commits: dict[int, list[str]] = {}
    for row in landing_read.landings:
        named = commits.setdefault(int(row["issue"]), [])
        if row["produced_commit"]:
            named.append(str(row["produced_commit"]))
    journalled: set[int] = {int(row["issue"]) for row in landing_read.landings}
    damaged: set[int] = set()
    for name in landing_read.malformed:
        issue, separator, file = name.partition("/")
        if separator and file == attribute_registry.LANDING_JOURNAL and issue.isdecimal():
            damaged.add(int(issue))
    return LandingJournals(
        {issue: tuple(named) for issue, named in commits.items()},
        frozenset(damaged),
        frozenset(journalled | damaged),
    )


def _landing_for(
    plan: Mapping[str, Any],
    issue: int | None,
    result: Mapping[str, Any] | None,
    repo: Path,
    journals: LandingJournals,
) -> ledger.Landing:
    """Return what this one dispatch landed: the journal's word where it has one.

    The landings journal owns the landing where it exists, and the git derivation is
    the fallback for issues it never covered — #563's ruling, because the derivation
    admits prose a journal would never name. The seat test still comes first, as it
    does in `ledger.materialise`: asking a `review` dispatch what it landed is a
    category error, and the row must say the seat lands nothing rather than reading
    as a weak git answer.
    """
    seat = plan.get("seat")
    base_sha = str(plan.get("base_sha") or "")
    if not ledger.seat_lands(seat):
        return ledger.Landing(None, 0, f"the {seat} seat lands nothing")
    if not issue:
        return ledger.Landing(None, 0, "the dispatch names no issue")
    if issue in journals.produced or issue in journals.damaged:
        return _journalled_landing(repo, issue, journals.produced.get(issue, ()), journals.damaged)
    return ledger.landed(repo, issue, base_sha, ledger.dispatch_start(plan, result))


def _issue_of(plan: Mapping[str, Any]) -> int | None:
    """Narrow the record's issue to a positive int, refusing nothing and crashing never.

    A record is untrusted input: `issue` can be absent, a string, a bool or a float,
    and every one of those is a null with a reason rather than a raised ValueError
    that would take the whole rebuild down with one malformed record.
    """
    value = plan.get("issue")
    if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
        return None
    return value


