def summary_lines(store: Mapping[str, Any], store_dir: Path) -> tuple[str, ...]:
    """Render the rebuild's own account of itself: coverage, damage, and the answer.

    Deterministic by construction — the lines derive only from the store, in sorted
    order, so the idempotence claim covers stdout as well as the file.
    """
    coverage = store["coverage"]
    lines = [
        f"observatory store={store_dir / STORE_NAME}",
        " ".join(
            (
                "coverage",
                f"dispatches={coverage['dispatches']}",
                f"with_telemetry={coverage['dispatches_with_telemetry']}",
                f"from_ledger_rows={coverage['dispatches_from_ledger_rows']}",
                f"with_spend={coverage['dispatches_with_spend']}",
                f"unbounded={len(coverage['dispatches_unbounded'])}",
                f"issues={coverage['issues']}",
                f"issues_with_landings={coverage['issues_with_landings']}",
                f"malformed_lines={coverage['malformed_lines']}",
            )
        ),
    ]
    lines.extend(
        f"malformed file={entry['file']} lines={entry['lines']}" for entry in store["malformed"]
    )
    # The flow line carries counts only. Lead time's percentiles are a query against
    # `flow_lead_time` — the one rendering path for them — and this line cannot emit a
    # mean in their place because it emits no lead-time figure at all.
    lines.append(
        " ".join(
            (
                "flow",
                f"work_items={coverage['work_items']}",
                f"landed={coverage['work_items_landed']}",
                f"open={coverage['work_items_open']}",
                f"abandoned={coverage['work_items_abandoned']}",
                f"stopped={coverage['work_items_stopped']}",
            )
        )
    )
    # The rework line states what the ranking rests on rather than presenting a
    # confident order: `round_zero` against `loops` is the key's own spread — most
    # issues sit at round zero, so the key barely varies and a key that does not vary
    # cannot rank — and `key_varies=no` says exactly that when it is true. The
    # sample-limit marker is the ADR's own account of its figures: the "20 to 30
    # landings" estimate carries no power calculation, base rate or effect size, so the
    # output names it an estimate rather than a measurement (ADR-0071 ruling 6).
    ranked_rows = [row for row in store["profile_rework"] if row["ranked"]]
    key_values = {row["rounds_per_landing"] for row in ranked_rows}
    lines.append(
        " ".join(
            (
                "rework",
                f"ranked_seats={','.join(sorted(RANKED_SEATS))}",
                f"loops={coverage['review_loops']}",
                f"round_zero={coverage['review_loops_round_zero']}",
                f"ranked_profiles={len(ranked_rows)}",
                f"key_varies={'yes' if len(key_values) > 1 else 'no'}",
                "measures=description",
                "sample_limit=estimate_not_measurement",
            )
        )
    )
    lines.extend(f"unreadable loop issue={issue}" for issue in coverage["review_loops_unreadable"])
    # The stage line carries counts and the boundary's own name, never a yield: the
    # per-stage rates and the product over them are a query against `stage_first_pass`,
    # and a summary yield over stages whose undetermined arrivals vary would be the
    # confident number the boundary column exists to qualify.
    lines.append(
        " ".join(
            (
                "stages",
                f"journals={coverage['stage_journals']}",
                f"arrivals={coverage['stage_arrivals']}",
                f"undetermined={coverage['stage_arrivals_undetermined']}",
                "history=journalled_only",
            )
        )
    )
    # The landings line carries the two counts that must not be mistaken for each
    # other — raw events and distinct landings — and counts the landings the
    # never-alone check cannot run over: those whose relation set carries no
    # author, and those carrying a dispatch relation that resolves to no dispatch
    # row (#491; round 2, finding 1). No verdict is rendered here: the check
    # itself is a cookbook query over `landing_relations` joined to `dispatches`,
    # and a summary that pre-computed it would be a second rendering path for it.
    lines.append(
        " ".join(
            (
                "landings",
                f"journals={coverage['landing_journals']}",
                f"events={coverage['landing_events']}",
                f"distinct={coverage['landings']}",
                f"relations={coverage['landing_relations']}",
                "uncheckable="
                + str(
                    len(
                        {
                            *coverage["landings_without_authors"],
                            *coverage["landings_with_unresolved_relations"],
                        }
                    )
                ),
            )
        )
    )
    lines.append(
        " ".join(
            (
                "landing_coverage",
                f"rows={coverage['landing_rows']}",
                f"journalled={coverage['landing_rows_journalled']}",
                f"journal_less={coverage['landing_rows_journal_less']}",
                f"unrecoverable={len(coverage['unrecoverable_landings'])}",
                f"journal_coverage={coverage['landing_rows_journalled']}/{coverage['landing_rows']}",
            )
        )
    )
    lines.extend(
        f"unrecoverable_landing issue={row['issue']} reason={row['produced_commit_reason']}"
        for row in store["landings"]
        if row["produced_commit"] is None
    )
    # The queue-depth line states the sample's own coverage rather than a depth: no
    # queue renders a number here, because the depth that matters is the newest one
    # and a summary that pre-computed it would be a second rendering path for the
    # cookbook's query. What a reader must know before trusting a quiet system is
    # here — how many samples, over how many queues, how many carried no count, and
    # when the newest was taken (#492). One definition rides beside the counts:
    # `human_ruling` is the open above-Low set of loops still running, and a reader
    # without the registry at hand once took that count for every open finding
    # (#554) — under ADR-0077 the line is a claim, and the narrowing is part of it.
    lines.append(
        " ".join(
            (
                "queue_depth",
                f"samples={coverage['queue_depth_samples']}",
                f"queues={coverage['queue_depth_queues']}",
                f"uncounted={coverage['queue_depth_samples_uncounted']}",
                "last="
                + (
                    str(coverage["queue_depth_last_at"])
                    if coverage["queue_depth_last_at"] is not None
                    else "none"
                ),
                "human_ruling_scope=open_above_low_of_running_loops",
            )
        )
    )
    # The session line names the source's largest omission in its own words — the seat
    # the figure cannot see is the orchestrator, and `orchestrator=absent` says so
    # where a coverage count alone would read as completeness. `meter=` names the
    # money column for what it is: list price, never spend (#220).
    lines.append(
        " ".join(
            (
                "sessions",
                f"renders={coverage['session_renders']}",
                f"untimestamped={coverage['session_renders_untimestamped']}",
                f"without_session={coverage['session_renders_without_session_id']}",
                f"sessions={coverage['session_spend_sessions']}",
                f"periods={coverage['session_spend_periods']}",
                "orchestrator=absent",
                "meter=list_price_not_spend",
            )
        )
    )
    for row in store["issue_cost"]:
        cost = row["cost"]
        # Three facts, three renderings: a number is a cost, `uncalibrated` names a
        # meter no calibration exists for, `absent` names a calibrated meter whose
        # spend could not be derived — a pruned source renders absent, never cheap and
        # never uncalibrated (#146's live row did exactly this).
        if isinstance(cost, (int, float)):
            rendered = f"{cost:.4f}"
        elif row["meter"] == METER_CLAUDE:
            rendered = "absent"
        else:
            rendered = "uncalibrated"
        lines.append(
            " ".join(
                (
                    f"issue={row['issue']}",
                    f"lane={row['lane']}",
                    f"landed={str(bool(row['landed'])).lower()}",
                    f"dispatches={row['dispatches']}",
                    f"spend_dispatches={row['spend_dispatches']}",
                    f"out={row['output_tokens'] if row['output_tokens'] is not None else 'none'}",
                    f"meter={row['meter']}",
                    f"cost={rendered}",
                )
            )
        )
    lines.append(f"ok=rebuilt dispatches={coverage['dispatches']}")
    return tuple(lines)


# ---------------------------------------------------------------------------- querying


def connect(store_dir: Path) -> sqlite3.Connection:
    """Open the shipped store as SQL, via the standard library.

    The tables are the store's own tables with their own column names, so the
    cookbook's queries are queries against the store and not against a translation of
    it. Nulls keep their reason siblings, because SQL is where an absence is most
    easily misread as a zero. A store whose `schema` names another version refuses by
    name rather than being read until it breaks, because every other failure this
    module can produce is a refusal too.
    """
    document = json.loads((store_dir / STORE_NAME).read_text(encoding="utf-8"))
    found = document.get("schema") if isinstance(document, dict) else None
    if found != SCHEMA:
        # A `/1` store predates `work_items`, a `/5` one `stage_first_pass` and a `/6`
        # one the landings tables, and the KeyError their loads would raise on those
        # absent tables is a traceback where a named refusal belongs.
        raise _RefusedError(
            Refusal(
                "schema_mismatch",
                (f"found={found}", f"needed={SCHEMA}"),
                "Rebuild the store: `just observatory rebuild` over the same sources.",
            )
        )
    connection = sqlite3.connect(":memory:")
    for table, columns in (
        ("dispatches", DISPATCH_COLUMNS),
        ("issue_cost", ISSUE_COST_COLUMNS),
        ("work_items", WORK_ITEM_COLUMNS),
        ("issue_rework", ISSUE_REWORK_COLUMNS),
        ("profile_rework", PROFILE_REWORK_COLUMNS),
        ("stage_first_pass", STAGE_FIRST_PASS_COLUMNS),
        ("landings", LANDING_COLUMNS),
        ("landing_relations", LANDING_RELATION_COLUMNS),
        ("queue_depth", QUEUE_DEPTH_COLUMNS),
        ("session_period", SESSION_PERIOD_COLUMNS),
        ("period_overhead", PERIOD_OVERHEAD_COLUMNS),
        ("issue_summary", ISSUE_SUMMARY_COLUMNS),
    ):
        names = ", ".join(columns)
        connection.execute(f"CREATE TABLE {table} ({names})")
        placeholders = ", ".join("?" * len(columns))
        loaded = [
            tuple(
                json.dumps(value, sort_keys=True, separators=(",", ":"))
                if table == "issue_summary" and column == "costs"
                else value
                for column in columns
                for value in (row.get(column),)
            )
            for row in document[table]
        ]
        connection.executemany(
            f"INSERT INTO {table} ({names}) VALUES ({placeholders})",  # noqa: S608 — table and columns are this module's own constants, never input
            loaded,
        )
    connection.execute(FLOW_LEAD_TIME_VIEW)
    return connection


def query(store_dir: Path, sql: str) -> tuple[tuple[Any, ...], ...]:
    """Run one SQL statement against the shipped store and return its rows."""
    with connect(store_dir) as connection:
        return tuple(connection.execute(sql).fetchall())


# ------------------------------------------------------------------------------- main


def parse_args(argv: Sequence[str]) -> argparse.Namespace:
    """Read the command line, with the environment's twin for every path."""
    parser = argparse.ArgumentParser(description="The observatory store: rebuild and query.")
    parser.add_argument(
        "action", nargs="?", default="rebuild", choices=("rebuild", "query", "check")
    )
    parser.add_argument("sql", nargs="*", help="query: one SQL statement")
    parser.add_argument(
        "--dispatch-root",
        type=Path,
        default=Path(os.environ.get("CTI_DISPATCH_DIR", str(DEFAULT_DISPATCH_ROOT))),
    )
    parser.add_argument(
        "--export-dir",
        type=Path,
        default=Path(os.environ.get("CTI_OTEL_EXPORT_DIR", str(DEFAULT_EXPORT_DIR))),
    )
    parser.add_argument(
        "--store-dir",
        type=Path,
        default=Path(os.environ.get("CTI_OBSERVATORY_DIR", str(DEFAULT_STORE_DIR))),
    )
    parser.add_argument(
        "--review-root",
        type=Path,
        default=Path(os.environ.get("CTI_REVIEW_DIR", str(DEFAULT_REVIEW_ROOT))),
    )
    parser.add_argument(
        "--queue-dir",
        type=Path,
        default=Path(os.environ.get("CTI_QUEUE_DIR", str(DEFAULT_QUEUE_ROOT))),
    )
    parser.add_argument(
        "--spool",
        type=Path,
        default=Path(os.environ.get("CTI_QUOTA_SPOOL", str(DEFAULT_SPOOL))),
    )
    parser.add_argument("--summary-path", type=Path, default=None)
    parser.add_argument("--repo", type=Path, default=Path.cwd())
    return parser.parse_args(argv)


def main(  # noqa: C901, PLR0911, PLR0912 — three CLI actions each own their refusal boundary
    argv: Sequence[str] | None = None,
) -> int:
    """Run one action: rebuild the store, or query the one already shipped."""
    raw_argv = list(argv if argv is not None else sys.argv[1:])
    if raw_argv and raw_argv[0] == "backfill":
        return importlib.import_module("observatory_backfill").main(raw_argv[1:])
    args = parse_args(raw_argv)
    if args.action == "query":
        if not args.sql:
            print("refused=no_sql action=Pass one SQL statement.")  # noqa: T201
            return EXIT_REFUSED
        try:
            rows = query(args.store_dir, " ".join(args.sql))
        except _RefusedError as refused:
            for line in refused.refusal.lines():
                print(line, file=sys.stderr)  # noqa: T201
            return EXIT_REFUSED
        except (OSError, ValueError, sqlite3.Error) as error:
            print(f"refused=query_failed error={error}")  # noqa: T201
            return EXIT_REFUSED
        for row in rows:
            print("|".join(str(value) for value in row))  # noqa: T201
        return 0
    if args.action == "check":
        try:
            check_summary(
                args.dispatch_root,
                args.export_dir,
                args.review_root,
                args.spool,
                args.repo,
                args.queue_dir,
                args.summary_path,
            )
        except _RefusedError as refused:
            for line in refused.refusal.lines():
                print(line, file=sys.stderr)  # noqa: T201
            return EXIT_REFUSED
        except SummaryMismatchError as error:
            reported = _stale_summary_report(
                args.repo,
                args.repo / SUMMARY_PATH if args.summary_path is None else args.summary_path,
                error,
            )
            if reported is not None:
                for line in reported:
                    print(line)  # noqa: T201 — the gate reader needs the stale state
                return 0
            print(f"refused={error.kind} detail={error.detail}", file=sys.stderr)  # noqa: T201
            return EXIT_REFUSED
        print(f"observatory_summary=ok path={args.summary_path or args.repo / SUMMARY_PATH}")  # noqa: T201
        return 0
    # Read the committed projection before the rebuild overwrites it: the row
    # accounting below is the regeneration's own account of what it changed,
    # quoted from the rebuild rather than from whoever writes the message (#571).
    # Unreadable is not absent (#574): a projection that exists but cannot be
    # read qualifies the counts under its own marker rather than passing as no
    # projection, so removals are never uncounted behind a false absence. A
    # `UnicodeDecodeError` is not an `OSError` and escapes to fail loudly.
    previous = ""
    previous_state = "absent"
    try:
        previous = (args.repo / SUMMARY_PATH).read_text(encoding="utf-8")
        previous_state = "present"
    except FileNotFoundError:
        pass
    except OSError:
        previous_state = "unreadable"
    try:
        store = rebuild(
            args.dispatch_root,
            args.export_dir,
            args.review_root,
            args.spool,
            args.repo,
            args.store_dir,
            args.queue_dir,
        )
    except _RefusedError as refused:
        for line in refused.refusal.lines():
            print(line, file=sys.stderr)  # noqa: T201
        return EXIT_REFUSED
    for line in summary_lines(store, args.store_dir):
        print(line)  # noqa: T201
    added, moved, removed = summary_row_changes(previous, render_summary(store))
    print(  # noqa: T201 — the row accounting is the output; the message quotes it (#571)
        f"summary_rows previous={previous_state} added={added} moved={moved} removed={removed}"
    )
    return 0


if __name__ == "__main__":  # pragma: no cover - the seam
    raise SystemExit(main())
