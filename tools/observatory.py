def _end_state_for(
    items: Sequence[ledger.Item],
    result_read: tuple[Mapping[str, Any] | None, str | None],
    ledger_row: Mapping[str, Any] | None,
    telemetry_source: str,
    export_path: Path,
) -> ledger.EndState | None:
    """Type how this dispatch ended, reusing `ledger`'s reader wherever one applies.

    The export-present case is `ledger.type_end_state` itself — the existing vocabulary
    and the existing order of tests. A pruned dispatch is typed from the surviving row's
    own `end_state` block, because the records the typing would have read are gone; a
    row without the block is a null with a reason, never a guessed class. A dispatch with
    no telemetry at all keeps the same reader over no records, which is what that reader
    already says about silence: nothing, by name. `result_read` is `ledger.read_json`'s
    whole return, carried as one value so the `None` names its own condition (#569).
    """
    result, result_condition = result_read
    if telemetry_source == SOURCE_EXPORT:
        return ledger.type_end_state(
            items,
            result,
            ledger.Source(SOURCE_EXPORT, export_path),
            result_condition=result_condition,
        )
    if telemetry_source == SOURCE_LEDGER_ROW:
        block = ledger_row.get("end_state") if ledger_row is not None else None
        state = block.get("class") if isinstance(block, dict) else None
        if isinstance(state, str) and state:
            return ledger.EndState(state, "read from the materialised ledger row", ())
        return None
    return ledger.type_end_state(
        [], result, ledger.Source(SOURCE_ABSENT, None), result_condition=result_condition
    )


def _parse_moment(value: object) -> datetime | None:
    """Read one instant from a record, strictly ISO, or nothing.

    The same tolerance `ledger.dispatch_start` gives a start: a naive string is an
    instant assumed UTC rather than a dropped value, because a dropped timestamp is
    a hole in the occupancy series this reader exists not to make. Anything that is
    not a parseable string is an absence its caller names.
    """
    if not isinstance(value, str) or not value:
        return None
    try:
        parsed = datetime.fromisoformat(value)
    except ValueError:
        return None
    return parsed if parsed.tzinfo is not None else parsed.replace(tzinfo=UTC)


def _bounded_end(
    ended: datetime | None,
    own_start: datetime | None,
    absent_reason: str,
) -> tuple[datetime | None, str | None]:
    """Apply the occupancy view's both-bounds rule to one candidate end (#485 round 2).

    An end bounds a span only beside a start the same run wrote: a result that
    recorded no `started_at` of its own would pair its end with the plan's
    `planned_at` — the launch attempt, never the work — so the pair attests no span
    however plausible the arithmetic over it looks. Eleven closeouts shaped exactly
    that way held 58% of the live store's `used` over the research window until
    round 2 rejected them by this record-shape rule, never by a list of ids
    (#485's review).
    """
    if ended is None:
        return None, absent_reason
    if own_start is None:
        return None, NO_END_NO_OWN_START_REASON
    return ended, None


